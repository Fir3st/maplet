import test from 'node:test';
import assert from 'node:assert/strict';
import { crs, type PointGeometry, type Position } from '../../src/index.ts';
import { makeMap } from '../helpers/fixture.ts';

const point = (id: string) => ({ id, position: { x: 0, y: 0 }, properties: { name: id } });
const line = [{ id: 'route', positions: [{ x: -1, y: 0 }, { x: 1, y: 0 }] }];
const polygon = [{ id: 'area', rings: [[{ x: -1, y: -1 }, { x: 1, y: -1 }, { x: 0, y: 1 }]] }];
const planarMap = () => makeMap({ projection: crs.simple(), center: { x: 0, y: 0 }, zoom: 0 });

test('layer tree: map object helpers append collections to one shared base layer', async () => {
  const { map } = await planarMap();
  assert.deepEqual(map.layers.list(), [], 'the implicit container is lazy');
  const first = map.addPoints([point('a')]);
  const second = map.addPoints([point('b')]);
  const lines = map.addLines(line);
  const polygons = map.addPolygons(polygon);
  const base = map.base;
  assert.equal(map.base, base);
  assert.equal(base.kind, 'layer');
  assert.deepEqual(map.layers.list(), [base]);
  assert.deepEqual(base.layers.list(), [first, second, lines, polygons]);
  assert.equal(base.layers.get(first.id), first);
  for (const entry of base.layers.list()) assert.equal(entry.parentId, base.id);
  first.get('a')!.setPosition({ x: 0.5, y: 0.5 });
  assert.deepEqual(second.get('b')!.getPosition(), { x: 0, y: 0 });
  base.hide();
  assert.equal(map.debug.layerInstances(first.id), 0);
  assert.equal(map.debug.layerInstances(lines.id), 0);
  assert.equal(first.count(), 1);
  base.show();
  assert.equal(map.debug.layerInstances(first.id), 1);
  map.destroy();
});

test('layer tree: every layer contains mixed objects, shared labels and nested layers', async () => {
  const { map } = await planarMap();
  const places = map.addLayer({ id: 'places' });
  const addLayer = new Proxy(places, {}).addLayer;
  const local = addLayer({ id: 'local' });
  const points = places.addPoints([point('a')]);
  const lines = places.addLines(line);
  const polygons = local.addPolygons(polygon);
  const labels = local.addLabels(points.source);
  assert.equal(local.parentId, places.id);
  assert.deepEqual(map.layers.list(), [places]);
  assert.deepEqual(places.layers.list(), [local, points, lines]);
  assert.deepEqual(local.layers.list(), [polygons, labels]);
  assert.deepEqual(places.layers.list({ recursive: true }), [local, polygons, labels, points, lines]);
  assert.equal(map.layers.get(local.id), local, 'global discovery resolves descendants');
  assert.equal(places.layers.get(polygons.id), undefined, 'scoped discovery only resolves direct children');
  points.get('a')!.setProperties({ name: 'Renamed' });
  assert.equal(map.debug.layerLabels(labels.id)[0]?.text, 'Renamed');
  points.hide();
  places.hide();
  assert.equal(local.isVisible(), false);
  assert.equal(map.debug.layerInstances(polygons.id), 0);
  assert.deepEqual(map.debug.layerLabels(labels.id), []);
  places.show();
  assert.equal(local.isVisible(), true);
  assert.equal(points.isVisible(), false, 'ancestor toggles retain each collection flag');
  assert.ok(map.debug.layerInstances(polygons.id) > 0);
  map.destroy();
});

test('layer tree: lazy base starts below explicit layers and has a reserved root identity', async () => {
  const { map } = await planarMap();
  const foreground = map.addLayer({ id: 'foreground' });
  const above = foreground.addPoints([point('above')]);
  const below = map.addPoints([point('below')]);
  assert.deepEqual(map.layers.list(), [map.base, foreground]);
  assert.deepEqual(map.debug.layerOrder(), [below.id, above.id]);
  assert.throws(() => map.addLayer({ id: 'base' }), /reserved/);
  assert.throws(() => map.base.move({ into: foreground.id }), /root/);
  assert.throws(() => map.layers.move('base', { before: above.id }), /root/);
  assert.deepEqual(map.layers.list(), [map.base, foreground]);
  const oldBase = map.base;
  oldBase.remove();
  const replacement = map.addPoints([point('new')]);
  assert.equal(oldBase.removed, true);
  assert.notEqual(map.base, oldBase);
  assert.equal(replacement.parentId, 'base');
  assert.throws(() => oldBase.addPoints([point('stale')]), /removed/);
  map.destroy();
});

test('layer tree: sibling indexing, reparenting and cycle rejection preserve the actual tree', async () => {
  const { map } = await planarMap();
  const outer = map.addLayer({ id: 'outer' });
  const a = outer.addLayer({ id: 'a' });
  const b = outer.addLayer({ id: 'b' });
  const points = a.addPoints([point('p')]);
  b.move({ index: 0 });
  assert.equal(b.parentId, outer.id, 'an index move must not eject a child to the root');
  assert.deepEqual(outer.layers.list(), [b, a]);
  a.move({ before: a.id });
  assert.deepEqual(outer.layers.list(), [b, a], 'self-relative moves are no-ops');
  assert.throws(() => outer.move({ into: a.id }), /descendant/);
  assert.throws(() => outer.move({ after: points.id }), /subtree/);
  assert.deepEqual(outer.layers.list(), [b, a]);
  points.move({ into: b.id });
  assert.equal(points.parentId, b.id, 'collection wrappers expose the live parent, not a copied getter value');
  assert.deepEqual(a.layers.list(), []);
  assert.deepEqual(b.layers.list(), [points]);
  b.move({ into: null, index: 0 });
  assert.equal(b.parentId, null);
  outer.remove();
  assert.equal(points.removed, false, 'moved-out descendants survive removal of their former parent');
  assert.equal(points.count(), 1);
  map.destroy();
});

test('layer tree: subtree removal releases owned data, preserves shared data and invalidates old receivers', async () => {
  const { map } = await planarMap();
  const parent = map.addLayer({ id: 'parent' });
  const child = parent.addLayer({ id: 'child' });
  const points = child.addPoints([point('a')]);
  const first = points.get('a')!;
  first.on('click', () => {});
  const lines = parent.addLines(line);
  const outsideLabels = map.addLabels(points.source);
  const explicit = map.data.vector<PointGeometry<Position>>({ id: 'caller-owned' });
  child.addPoints(explicit);
  parent.remove();
  assert.equal(parent.removed, true);
  assert.equal(child.removed, true);
  assert.equal(points.removed, true);
  assert.equal(first.removed, true);
  assert.equal(map.layers.get(child.id), undefined);
  assert.equal(map.data.get(lines.sourceId), undefined);
  assert.ok(map.data.get(points.sourceId), 'an outside shared layer retains the inline data');
  assert.equal(map.data.get(explicit.id), explicit, 'explicit sources remain caller-owned');
  const replacement = map.addLayer({ id: 'parent' });
  assert.throws(() => parent.addLayer(), /removed/);
  assert.throws(() => child.addPoints([point('bad')]), /removed/);
  assert.throws(() => child.layers.list(), /removed/);
  assert.throws(() => first.setPosition({ x: 1, y: 1 }), /removed/);
  assert.deepEqual(replacement.layers.list(), []);
  outsideLabels.remove();
  assert.equal(map.data.get(points.sourceId), undefined);
  map.destroy();
});

test('layer tree: explicit raster, WMS and source-backed render passes belong to their receiver', async () => {
  const { map } = await makeMap();
  const layer = map.addLayer({ id: 'background' });
  const child = layer.addLayer();
  const tiles = layer.addTiles('https://example.test/{z}/{x}/{y}.png');
  const wms = child.addWms('https://example.test/wms', { layers: 'test' });
  const source = map.data.vector({ id: 'imported' });
  const pass = child.addLayer({ type: 'fills', source });
  assert.equal(tiles.parentId, layer.id);
  assert.equal(wms.parentId, child.id);
  assert.equal(pass.parentId, child.id);
  assert.deepEqual(layer.layers.list(), [child, tiles]);
  layer.hide();
  assert.deepEqual(map.debug.layerTiles(tiles.id), []);
  layer.remove();
  assert.equal(tiles.removed, true);
  assert.equal(wms.removed, true);
  assert.equal(map.data.get(tiles.sourceId), undefined);
  assert.equal(map.data.get(wms.sourceId), undefined);
  assert.equal(map.data.get(source.id), source);
  map.destroy();
});

test('layer tree: an invalid receiver/parent cannot silently redirect objects to another layer', async () => {
  const { map } = await planarMap();
  const a = map.addLayer({ id: 'a' });
  const b = map.addLayer({ id: 'b' });
  assert.throws(() => a.addPoints([point('wrong')], { parent: b.id }), /receiving/);
  assert.throws(() => a.addLayer({ parent: b.id }), /receiving/);
  assert.throws(() => map.addLayer({ parent: 'missing' }), /not found/);
  assert.throws(() => map.addPoints([point('wrong')], { parent: 'missing' }), /not found/);
  assert.throws(() => map.addPoints([point('wrong')], { parent: '' }), /nonempty/);
  assert.throws(() => map.addLayer({ style: { radiusPx: 8 } } as never), /typed collections/);
  assert.throws(() => a.layers.remove(b.id), /not found/);
  assert.deepEqual(map.data.list(), []);
  assert.deepEqual(a.layers.list(), []);
  assert.deepEqual(b.layers.list(), []);
  assert.equal('groups' in map, false, 'logical layers replace the separate grouping API');
  map.destroy();
});

test('layer tree: nested imported sources do not create eager per-feature objects or reads', async () => {
  const { map } = await planarMap();
  const source = map.data.vector<PointGeometry<Position>>({ id: 'large' });
  await source.importColumnar({ kind: 'point', positions: new Float64Array(100_000 * 2) });
  const get = source.features.get;
  source.features.get = () => { throw new Error('unexpected per-feature snapshot'); };
  const parent = map.addLayer();
  const child = parent.addLayer();
  const points = child.addPoints(source);
  assert.equal(points.count(), 100_000);
  parent.hide();
  parent.show();
  assert.equal(points.count(), 100_000);
  source.features.get = get;
  map.destroy();
  assert.throws(() => child.addLayer(), { code: 'destroyed' });
});
